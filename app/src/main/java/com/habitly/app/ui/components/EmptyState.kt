/** Centred icon, title, message and optional single action for screens with nothing to show yet. */
@Composable
fun EmptyState(
    icon: ImageVector,
    title: String,
    message: String,
    modifier: Modifier = Modifier,
    actionLabel: String? = null,
    onAction: (() -> Unit)? = null,
    extra: @Composable ColumnScope.() -> Unit = {},
) {
    Column(
        modifier = modifier.fillMaxWidth().padding(24.dp),
        horizontalAlignment = Alignment.CenterHorizontally,
    ) {
        Box(
            modifier = Modifier
                .size(64.dp)
                .clip(RoundedCornerShape(20.dp))
                .background(LocalHabitlyColors.current.surfaceRaised),
            contentAlignment = Alignment.Center,
        ) {
            Icon(icon, contentDescription = null, tint = MaterialTheme.colorScheme.primary, modifier = Modifier.size(28.dp))
        }
        Spacer(Modifier.height(16.dp))
        Text(
            text = title,
            style = MaterialTheme.typography.titleLarge,
            color = MaterialTheme.colorScheme.onSurface,
            textAlign = TextAlign.Center,
        )
        Spacer(Modifier.height(8.dp))
        Text(
            text = message,
            style = MaterialTheme.typography.bodyLarge,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
            textAlign = TextAlign.Center,
            modifier = Modifier.widthIn(max = 280.dp),
        )
        extra()
        if (actionLabel != null && onAction != null) {
            Spacer(Modifier.height(20.dp))
            PrimaryButton(text = actionLabel, onClick = onAction)
        }
    }
}

@Composable
private fun EmptyStatePreviewContent() {
    Surface(color = MaterialTheme.colorScheme.background) {
        EmptyState(
            icon = Icons.Rounded.GridView,
            title = "No habits yet",
            message = "Add your first habit and watch the grid fill in.",
            actionLabel = "New habit",
            onAction = {},
        )
    }
}

@Preview @Composable private fun EmptyStateDarkPreview() = HabitlyTheme(darkTheme = true) { EmptyStatePreviewContent() }
@Preview @Composable private fun EmptyStateLightPreview() = HabitlyTheme(darkTheme = false) { EmptyStatePreviewContent() }
